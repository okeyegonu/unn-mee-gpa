#!/usr/bin/env node
/**
 * Validates data/curriculum.json and regenerates:
 *
 *   data/curriculum.flat.json      machine-readable flat course list
 *   docs/curriculum-validation.md  human-readable validation table + report
 *
 * Exits non-zero if any error (as opposed to warning) is found.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

import { validateCurriculum, flattenCurriculum } from '../src/curriculum.js';
import { buildGradeTemplates } from '../src/grading.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const doc = JSON.parse(await readFile(resolve(root, 'data/curriculum.json'), 'utf8'));
const { errors, warnings, info, courses } = validateCurriculum(doc);

/* ---------------------------------------------------- machine-readable ---- */

const flat = {
  curriculum_id: doc.curriculum_id,
  curriculum_version: doc.curriculum_version,
  institution: doc.institution,
  department: doc.department,
  programme: doc.programme,
  programme_track: doc.programme_track,
  generated_at: new Date().toISOString(),
  generated_by: 'tools/validate-curriculum.mjs',
  course_count: courses.length,
  grade_scale: doc.grade_scale,
  grade_templates: buildGradeTemplates(courses.map((c) => c.units)),
  courses: courses.map((c) => ({
    id: c.id, code: c.code, title: c.title, units: c.units,
    year: c.year, semester: c.semester,
    group_id: c.groupId, group_label: c.groupLabel, group_type: c.groupType,
    category: c.category, legacy_code: c.legacyCode,
    units_unknown: c.unitsUnknown, title_unknown: c.titleUnknown,
    source_id: c.sourceId, notes: c.notes,
  })),
};
await writeFile(resolve(root, 'data/curriculum.flat.json'), JSON.stringify(flat, null, 2) + '\n');

/* ----------------------------------------------------- human-readable ----- */

const L = [];
L.push('# Curriculum extraction — validation report');
L.push('');
L.push(`Generated by \`tools/validate-curriculum.mjs\` on ${new Date().toISOString().slice(0, 10)}.`);
L.push('');
L.push(`- **Institution:** ${doc.institution}`);
L.push(`- **Department:** ${doc.department}`);
L.push(`- **Programme:** ${doc.programme} — ${doc.programme_track}`);
L.push(`- **Curriculum version:** \`${doc.curriculum_version}\` (id \`${doc.curriculum_id}\`)`);
L.push(`- **Courses extracted:** ${courses.length}`);
L.push('');
for (const s of doc.sources ?? []) {
  L.push(`- **Source (${s.applies_to.join(', ')}):** \`${s.document}\` — ${s.description}`);
}
L.push('');
L.push(`> ${doc.provenance_note}`);
L.push('');

L.push('## Extracted courses');
L.push('');
for (const year of doc.years) {
  L.push(`### ${year.label}`);
  L.push('');
  for (const sem of year.semesters) {
    L.push(`#### ${sem.label}`);
    L.push('');
    L.push('| Course code | Course title | Units | Group | Category |');
    L.push('|---|---|---:|---|---|');
    for (const g of sem.groups) {
      for (const c of g.courses) {
        const title = c.title ?? '_not stated in source_';
        const units = Number.isFinite(c.units) ? c.units : '**?**';
        L.push(`| \`${c.code}\` | ${title} | ${units} | ${g.type === 'elective' ? g.label : 'Compulsory'} | ${c.category ?? ''} |`);
      }
    }
    const here = courses.filter((c) => c.year === year.year && c.semester === sem.semester);
    const comp = here.filter((c) => c.groupType !== 'elective').reduce((a, c) => a + (c.units ?? 0), 0);
    const electiveReq = (sem.groups.find((g) => g.type === 'elective')?.choose_units) ?? 0;
    L.push('');
    L.push(`Compulsory units listed: **${comp}**` +
      (electiveReq ? ` &nbsp;·&nbsp; elective units required: **${electiveReq}**` : '') +
      (sem.stated_total_units != null ? ` &nbsp;·&nbsp; total stated in source: **${sem.stated_total_units}**` : '') +
      (sem.printed_total_units != null && sem.printed_total_units !== sem.stated_total_units
        ? ` &nbsp;·&nbsp; superseded printed total: ${sem.printed_total_units}` : ''));
    if (sem.elective_rule) L.push('');
    if (sem.elective_rule) L.push(`Elective rule: _${sem.elective_rule}_`);
    L.push('');
  }
}

L.push('## Checks');
L.push('');
const section = (title, items, empty) => {
  L.push(`### ${title} (${items.length})`);
  L.push('');
  if (items.length === 0) L.push(empty);
  else for (const i of items) L.push(`- ${i}`);
  L.push('');
};
section('Errors', errors, '_None._');
section('Warnings and reported ambiguities', warnings, '_None._');
section('Informational', info, '_None._');

L.push('## Ambiguities in the source documents');
L.push('');
L.push('These are reported rather than guessed at, as required by the specification.');
L.push('');
L.push('1. **`PHY 104` and `STA 112` (First Year, Second Semester) have no unit load on the form.** Both appear in');
L.push('   the handwritten revision, but no number is written against them in the unit column, and no total is');
L.push('   written for the revised second semester either, so the values could not be recovered by arithmetic.');
L.push('   **Resolved on 2026-09-17:** the department supplied `PHY 104` = 2 units and `STA 112` = 3 units. Both');
L.push('   are marked `"units_source": "supplied_by_department"` in `data/curriculum.json` and recorded under');
L.push('   `amendments`, so it stays clear that these two figures were provided rather than extracted. With them');
L.push('   in place the revised second semester totals 16 units, matching the revised first semester.');
L.push('2. **Most revised First Year course titles are not stated.** The form lists codes only. Where a new code');
L.push('   plainly replaces a struck-out printed course (for example `MTH 101` over `MTH 111`), that course’s');
L.push('   printed title has been carried across and marked `"title_source": "inherited_from_replaced_course"`.');
L.push('   Where there is no such predecessor — `PHY 103`, `GET 101` and the whole of the revised second');
L.push('   semester — the title is left `null` rather than invented.');
L.push('3. **The First Year and the later years come from different revisions of the programme.** The handwritten');
L.push('   form uses the newer numbering (`MTH 101`, `GST 111`, `MEE 101`, `GET 102`); the 2023 bachelors');
L.push('   document still prints the older numbering for First Year (`MTH 111`, `GSP 101`, `EGR 101`) and uses');
L.push('   `MEE/EGR/CVE/EEE/GSP` codes throughout Years 2–5. Years 2–5 are reproduced exactly as printed.');
L.push('4. **First Year, Second Semester: printed list versus handwritten list.** The printed list');
L.push('   (`MTH 122`, `CHM 112`, `CHM 122`, `PHY 116`, `PHY 124`, `GSP 102`, `ENGR 102`) is not struck out on');
L.push('   the form, but a complete parallel list in the revised numbering is written beside it. The handwritten');
L.push('   list is treated as the current one; the printed list is retained in the data file under');
L.push('   `superseded_printed_list` so the decision can be reviewed and reversed.');
L.push('5. **`GSP 111` (The Use of Library and Study Skills, 2 units) is struck out with no replacement.** It is');
L.push('   recorded under `removed_from_earlier_revision` and does not appear in the calculator.');
L.push('6. **Fifth Year electives are option areas, not a free pool.** Option A (Thermal and Fluids) and Option B');
L.push('   (Design, Materials and Manufacturing) are alternatives: a student chooses two courses (6 units) in the');
L.push('   first semester and one course (3 units) in the second from *one* option area. Both option areas are');
L.push('   listed in full and the courses are marked as electives; the calculator counts whichever electives the');
L.push('   student actually enters a grade for, and does not enforce the choice rule.');
L.push('');

L.push('## How to correct this data');
L.push('');
L.push('Edit `data/curriculum.json` only — the GPA engine, the storage layer and the interface read it at');
L.push('runtime and contain no course definitions. Then run `npm run validate` to regenerate this report and');
L.push('`data/curriculum.flat.json`. If the change is substantive, raise `curriculum_version`; results saved');
L.push('under the previous version are kept separately and are never overwritten.');
L.push('');

await writeFile(resolve(root, 'docs/curriculum-validation.md'), L.join('\n'));

/* ------------------------------------------------------------- console ---- */

const pad = (s, n) => String(s).padEnd(n);
console.log(`\n${doc.programme} — ${doc.programme_track}`);
console.log(`${doc.institution}, ${doc.department}`);
console.log(`curriculum ${doc.curriculum_id} version ${doc.curriculum_version}\n`);

for (const year of doc.years) {
  for (const sem of year.semesters) {
    const here = courses.filter((c) => c.year === year.year && c.semester === sem.semester);
    console.log(`${year.label} / ${sem.label}`);
    console.log(`  ${pad('CODE', 10)}${pad('UNITS', 7)}TITLE`);
    for (const c of here) {
      console.log(`  ${pad(c.code, 10)}${pad(c.unitsUnknown ? '?' : c.units, 7)}${c.title ?? '(title not stated in source)'}`);
    }
    console.log('');
  }
}

console.log(`Courses: ${courses.length}`);
console.log(`Errors:   ${errors.length}`);
for (const e of errors) console.log(`  ERROR   ${e}`);
console.log(`Warnings: ${warnings.length}`);
for (const w of warnings) console.log(`  WARN    ${w}`);
console.log(`Notes:    ${info.length}`);
for (const i of info) console.log(`  note    ${i}`);
console.log('\nWrote data/curriculum.flat.json and docs/curriculum-validation.md');

process.exit(errors.length > 0 ? 1 : 0);
